"""Missions store: schema + seed + service functions (the hold state-machine).

Pure SQLite, sqlite idiom (`?` placeholders) so the PostgreSQL adapter in db.py
can translate transparently. Reads take a short-lived connection; writes go
through the shared write connection under the runtime lock (see routers/missions.py).
The same tables are read/written by the standalone missions MCP process.
"""
import json
import random
import uuid
from datetime import datetime, timezone
from typing import List, Optional

from flightdeck import db

STATUSES = ("INBOX", "TODO", "IN_FLIGHT", "DONE")
# kind separates a NOTE (memory / reference an agent reads) from a TODO (task an
# agent acts on). Independent of status/column. Agents filter on it.
KINDS = ("NOTE", "TODO")


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _new_id() -> str:
    return "m_" + uuid.uuid4().hex[:8]


# Presence liveness: a hold is ACTIVE while its heartbeat is fresh, HELD when the
# session has gone quiet, STALE when it likely died without releasing.
ACTIVE_MAX_S = 90
HELD_MAX_S = 600


def _age_seconds(iso: Optional[str]):
    if not iso:
        return None
    try:
        t = datetime.strptime(iso, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
        return (datetime.now(timezone.utc) - t).total_seconds()
    except Exception:
        return None


def _hold_state(beat: Optional[str]) -> str:
    age = _age_seconds(beat)
    if age is None or age < ACTIVE_MAX_S:
        return "ACTIVE"
    if age < HELD_MAX_S:
        return "HELD"
    return "STALE"


