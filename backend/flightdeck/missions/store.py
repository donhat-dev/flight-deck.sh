def _seed_if_empty(conn) -> None:
    n = conn.execute("SELECT COUNT(*) AS c FROM missions").fetchone()
    if n and n["c"]:
        return
    now = _now()
    for status, title, note, tags, prio, hold, kind, hname in _SEED:
        mid = _new_id()
        conn.execute(
            "INSERT INTO missions (id, status, title, note, tags, priority, kind, "
            "hold_session, hold_name, hold_state, hold_since, hold_beat, is_read, created_at, updated_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (mid, status, title, note, json.dumps(tags), prio, kind,
             hold, hname, "ACTIVE" if hold else None, now if hold else None, now if hold else None,
             1 if status == "DONE" else 0, now, now),
        )
        _log(conn, mid, None, "CREATED", now)
        if hold:
            _log(conn, mid, hold, "CLAIMED", now)
    conn.commit()
