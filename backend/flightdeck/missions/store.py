def _log(conn, mission_id: str, session_id: Optional[str], action: str, at: Optional[str] = None) -> None:
    conn.execute(
        "INSERT INTO mission_log (mission_id, session_id, action, at) VALUES (?, ?, ?, ?)",
        (mission_id, session_id, action, at or _now()),
    )


def _row_to_mission(r, log: Optional[list] = None) -> dict:
    hold = None
    if r["hold_session"]:
        beat = r["hold_beat"] or r["hold_since"]
        age = _age_seconds(beat)
        hold = {"session_id": r["hold_session"], "name": r["hold_name"] or r["hold_session"],
                "state": _hold_state(beat), "since": r["hold_since"], "beat": beat,
                "beat_age": int(age) if age is not None else None}
    m = {
        "id": r["id"],
        "status": r["status"],
        "title": r["title"],
        "note": r["note"],
        "tags": json.loads(r["tags"] or "[]"),
        "priority": r["priority"],
        "kind": r["kind"],
        "parent_id": r["parent_id"],
        "is_read": bool(r["is_read"]),
        "hold": hold,
        "created_at": r["created_at"],
        "updated_at": r["updated_at"],
    }
    if log is not None:
        m["log"] = log
    return m


_STATUS_ORDER = "CASE status WHEN 'INBOX' THEN 0 WHEN 'TODO' THEN 1 " \
                "WHEN 'IN_FLIGHT' THEN 2 WHEN 'DONE' THEN 3 ELSE 4 END"


def list_missions(conn) -> dict:
    rows = conn.execute(
        "SELECT * FROM missions ORDER BY " + _STATUS_ORDER + ", updated_at DESC"
    ).fetchall()
    return {
        "missions": [_row_to_mission(r) for r in rows],
        "sessions": list_sessions(conn),
    }


def get_mission(conn, mid: str) -> Optional[dict]:
    r = conn.execute("SELECT * FROM missions WHERE id=?", (mid,)).fetchone()
    if not r:
        return None
    log_rows = conn.execute(
        "SELECT session_id, action, at FROM mission_log WHERE mission_id=? ORDER BY at DESC, id DESC",
        (mid,),
    ).fetchall()
    log = [{"session_id": lr["session_id"], "action": lr["action"], "at": lr["at"]} for lr in log_rows]
    m = _row_to_mission(r, log=log)
    child_rows = conn.execute(
        "SELECT * FROM missions WHERE parent_id=? ORDER BY " + _STATUS_ORDER + ", updated_at DESC", (mid,)
    ).fetchall()
    m["children"] = [_row_to_mission(c) for c in child_rows]
    return m


def list_sessions(conn) -> List[dict]:
    """Live holders, derived from missions (one hold per session in MVP)."""
    rows = conn.execute(
        "SELECT hold_session, hold_since, hold_beat, id FROM missions "
        "WHERE hold_session IS NOT NULL ORDER BY hold_since DESC"
    ).fetchall()
    return [{"session_id": r["hold_session"], "state": _hold_state(r["hold_beat"] or r["hold_since"]),
             "mission_id": r["id"], "since": r["hold_since"]} for r in rows]


def create_mission(conn, title: str, note: str = "", tags: Optional[list] = None,
                   priority: str = "NORMAL", status: str = "INBOX",
                   kind: str = "TODO", parent_id: Optional[str] = None,
                   claim_session: Optional[str] = None) -> dict:
    mid = _new_id()
    now = _now()
    status = status if status in STATUSES else "INBOX"
    kind = kind if kind in KINDS else "TODO"
    conn.execute(
        "INSERT INTO missions (id, status, title, note, tags, priority, kind, parent_id, "
        "hold_session, hold_name, hold_state, hold_since, hold_beat, is_read, created_at, updated_at) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (mid, status, title, note or "", json.dumps(tags or []), priority or "NORMAL", kind, parent_id,
         None, None, None, None, None, 0, now, now),
    )
    _log(conn, mid, None, "CREATED", now)
    conn.commit()
    if claim_session:
        return claim(conn, mid, claim_session)
    return get_mission(conn, mid)


def update_mission(conn, mid: str, **fields) -> Optional[dict]:
    allowed = {"status", "title", "note", "tags", "priority", "kind"}
    sets, vals = [], []
    for k, v in fields.items():
        if k not in allowed or v is None:
            continue
        if k == "tags":
            v = json.dumps(v)
        if k == "status" and v not in STATUSES:
            continue
        if k == "kind" and v not in KINDS:
            continue
        sets.append(k + "=?")
        vals.append(v)
    if not sets:
        return get_mission(conn, mid)
    if fields.get("status") == "DONE":
        sets.append("is_read=?")   # newly done -> unread (glows until opened)
        vals.append(0)
    sets.append("updated_at=?")
    vals.append(_now())
    vals.append(mid)
    cur = conn.execute("UPDATE missions SET " + ", ".join(sets) + " WHERE id=?", vals)
    conn.commit()
    if cur.rowcount == 0:
        return None
    # An edit by the holder is activity -> refresh the heartbeat so the card stays ACTIVE.
    conn.execute("UPDATE missions SET hold_beat=? WHERE id=? AND hold_session IS NOT NULL", (_now(), mid))
    conn.commit()
    return get_mission(conn, mid)


def mark_read(conn, mid: str) -> Optional[dict]:
    """Mark a mission read (opening a DONE one stops its glow, dims it)."""
    conn.execute("UPDATE missions SET is_read=1 WHERE id=?", (mid,))
    conn.commit()
    return get_mission(conn, mid)


def delete_mission(conn, mid: str) -> bool:
    """Delete a mission and its log. Returns True if a row was removed."""
    cur = conn.execute("DELETE FROM missions WHERE id=?", (mid,))
    conn.execute("DELETE FROM mission_log WHERE mission_id=?", (mid,))
    conn.execute("UPDATE missions SET parent_id=NULL WHERE parent_id=?", (mid,))  # orphan children, no dangling
    conn.commit()
    return (cur.rowcount or 0) > 0


def claim(conn, mid: str, session_id: str, name: Optional[str] = None) -> Optional[dict]:
    """Set an ACTIVE hold for session_id, with an optional friendly display name.
    Overwrites any existing hold (take-over)."""
    r = conn.execute("SELECT id FROM missions WHERE id=?", (mid,)).fetchone()
    if not r:
        return None
    now = _now()
    conn.execute(
        "UPDATE missions SET hold_session=?, hold_name=?, hold_state='ACTIVE', "
        "hold_since=?, hold_beat=?, updated_at=? WHERE id=?",
        (session_id, name or session_id, now, now, now, mid),
    )
    _log(conn, mid, session_id, "CLAIMED", now)
    conn.commit()
    return get_mission(conn, mid)


def release(conn, mid: str) -> Optional[dict]:
    r = conn.execute("SELECT hold_session FROM missions WHERE id=?", (mid,)).fetchone()
    if not r:
        return None
    now = _now()
    conn.execute(
        "UPDATE missions SET hold_session=NULL, hold_name=NULL, hold_state=NULL, "
        "hold_since=NULL, hold_beat=NULL, updated_at=? WHERE id=?",
        (now, mid),
    )
    _log(conn, mid, r["hold_session"], "RELEASED", now)
    conn.commit()
    return get_mission(conn, mid)


def land(conn, mid: str) -> Optional[dict]:
    r = conn.execute("SELECT hold_session FROM missions WHERE id=?", (mid,)).fetchone()
    if not r:
        return None
    now = _now()
    conn.execute(
        "UPDATE missions SET status='DONE', is_read=0, hold_session=NULL, hold_name=NULL, "
        "hold_state=NULL, hold_since=NULL, hold_beat=NULL, updated_at=? WHERE id=?",
        (now, mid),
    )
    _log(conn, mid, r["hold_session"], "LANDED", now)
    conn.commit()
    return get_mission(conn, mid)


